// Command gen writes the store's dialect-neutral types and the mechanical
// converters each dialect implementation uses.
//
// sqlc generates one package per engine, with distinct-but-structurally-equal
// parameter and row types. The store owns dialect-neutral copies
// (internal/gen/storetypes, re-exported by internal/store/types.go); the
// SQLite and PostgreSQL store implementations convert at their own query call
// sites. This tool writes those neutral types, the aliases and the converters,
// and fails if either schema stops mapping a column to the same Go type.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
)

type field struct {
	Name string
	Type string
}

type dialect struct {
	name string // sqlite / pg
	pkg  string // sqlitedb / pgdb
	out  string
	from string // fromSqlite / fromPg
}

func main() {
	sqliteDir := flag.String("sqlite", "internal/gen/sqlite", "sqlc SQLite output")
	pgDir := flag.String("pg", "internal/gen/pg", "sqlc PostgreSQL output")
	typesOut := flag.String("types-out", "internal/gen/storetypes/types.go", "neutral type package")
	aliasesOut := flag.String("aliases-out", "internal/store/types.go", "store package aliases")
	sqliteConv := flag.String(
		"sqlite-convert-out",
		"internal/store/sqlite_convert_gen.go",
		"SQLite converters",
	)
	pgConv := flag.String(
		"pg-convert-out",
		"internal/store/pg_convert_gen.go",
		"PostgreSQL converters",
	)
	flag.Parse()

	sqliteTypes, err := loadTypes(*sqliteDir)
	must(err)
	pgTypes, err := loadTypes(*pgDir)
	must(err)

	must(writeTypes(*typesOut, sqliteTypes))
	must(writeAliases(*aliasesOut, sqliteTypes))

	for _, d := range []dialect{
		{name: "sqlite", pkg: "sqlitedb", out: *sqliteConv, from: "fromSqlite"},
		{name: "pg", pkg: "pgdb", out: *pgConv, from: "fromPg"},
	} {
		types, other := sqliteTypes, pgTypes
		if d.name == "pg" {
			types, other = pgTypes, sqliteTypes
		}
		must(writeConverters(d, types, other))
	}
}

func writeTypes(path string, types map[string][]field) error {
	var b bytes.Buffer
	fmt.Fprint(&b, `// Code generated by internal/store/gen. DO NOT EDIT.

// Package storetypes holds the dialect-neutral row and parameter types the
// store interface and its two dialect implementations share.
package storetypes

import "database/sql"

`)
	for _, name := range sortedKeys(types) {
		fmt.Fprintf(&b, "type %s struct {\n", name)
		for _, f := range types[name] {
			fmt.Fprintf(&b, "\t%s %s\n", f.Name, f.Type)
		}
		fmt.Fprint(&b, "}\n\n")
	}
	return writeFormatted(path, b.Bytes())
}

func writeAliases(path string, types map[string][]field) error {
	var b bytes.Buffer
	fmt.Fprint(&b, `// Code generated by internal/store/gen. DO NOT EDIT.

package store

// Dialect-neutral aliases re-exported from the generated storetypes package.
// The Store interface, the services and both dialect implementations use
// these names; no SQLite or PostgreSQL generated type appears in the public
// store surface.
//
// Generated by `+"`make sqlc`"+`; do not edit by hand.

import storetypes "cherrypi.vladfaust.com/agency/internal/gen/storetypes"

`)
	for _, name := range sortedKeys(types) {
		fmt.Fprintf(&b, "type %s = storetypes.%s\n", name, name)
	}
	return writeFormatted(path, b.Bytes())
}

func writeConverters(d dialect, types, other map[string][]field) error {
	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by internal/store/gen. DO NOT EDIT.

package store

import %[2]s "cherrypi.vladfaust.com/agency/internal/gen/%[1]s"

`, d.name, d.pkg)

	for _, name := range sortedKeys(types) {
		fields := types[name]
		if !sameFields(fields, other[name]) {
			continue
		}
		fmt.Fprintf(
			&b,
			"func %s%s(v %s.%s) %s {\n\treturn %s{\n",
			d.from,
			name,
			d.pkg,
			name,
			name,
			name,
		)
		for _, f := range fields {
			fmt.Fprintf(&b, "\t\t%s: v.%s,\n", f.Name, f.Name)
		}
		fmt.Fprint(&b, "\t}\n}\n\n")

		fmt.Fprintf(
			&b,
			"func %s%sSlice(vs []%s.%s) []%s {\n\tout := make([]%s, 0, len(vs))\n\tfor _, v := range vs {\n\t\tout = append(out, %s%s(v))\n\t}\n\treturn out\n}\n\n",
			d.from,
			name,
			d.pkg,
			name,
			name,
			name,
			d.from,
			name,
		)
	}
	return writeFormatted(d.out, b.Bytes())
}

func sameFields(a, b []field) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i].Name != b[i].Name || a[i].Type != b[i].Type {
			return false
		}
	}
	return true
}

func loadTypes(dir string) (map[string][]field, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	out := map[string][]field{}
	for _, path := range files {
		fset := token.NewFileSet()
		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			return nil, err
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				st, ok := ts.Type.(*ast.StructType)
				if !ok || ts.Name.Name == "Queries" {
					continue
				}
				var fields []field
				for _, f := range st.Fields.List {
					typ := exprString(fset, f.Type)
					if len(f.Names) == 0 {
						fields = append(fields, field{Name: "", Type: typ})
						continue
					}
					for _, n := range f.Names {
						fields = append(fields, field{Name: n.Name, Type: typ})
					}
				}
				out[ts.Name.Name] = fields
			}
		}
	}
	return out, nil
}

func exprString(fset *token.FileSet, expr ast.Expr) string {
	var b bytes.Buffer
	if err := printer.Fprint(&b, fset, expr); err != nil {
		fail("format expression: %v", err)
	}
	return b.String()
}

func sortedKeys[T any](m map[string]T) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func writeFormatted(path string, src []byte) error {
	formatted, err := format.Source(src)
	if err != nil {
		fmt.Fprintln(os.Stderr, string(src))
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, formatted, 0o644)
}

func must(err error) {
	if err != nil {
		fail("%v", err)
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "store/gen: "+format+"\n", args...)
	os.Exit(1)
}
