CREATE TABLE invitations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL CHECK (kind IN ('username', 'email', 'oidc', 'ldap')),
  
  username TEXT NOT NULL,
  
  actor_id BIGINT NOT NULL,
  -- E-mail invites: the invited address.
  email TEXT,
  -- OIDC/LDAP invites: the provider and the provider-side username to match.
  provider_id BIGINT,
  external_username TEXT,
  role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('admin', 'member')),
  -- E-mail invites: the hashed single-use acceptance token.
  token_hash BYTEA,
  invited_by_actor_id BIGINT,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  accepted_at BIGINT,
  revoked_at BIGINT
);


CREATE TABLE ldap_providers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL,
  name TEXT NOT NULL,
  enabled BIGINT NOT NULL DEFAULT 1 CHECK (enabled IN (0, 1)),
  host TEXT NOT NULL,
  port BIGINT NOT NULL DEFAULT 389,
  encryption TEXT NOT NULL DEFAULT 'none'
    CHECK (encryption IN ('none', 'starttls', 'ldaps')),
  insecure BIGINT NOT NULL DEFAULT 0 CHECK (insecure IN (0, 1)),
  base_dn TEXT NOT NULL DEFAULT '',
  bind_dn TEXT NOT NULL DEFAULT '',
  
  bind_password TEXT NOT NULL DEFAULT '',
  user_filter TEXT NOT NULL DEFAULT '(uid={username})',
  username_attr TEXT NOT NULL DEFAULT 'uid',
  email_attr TEXT NOT NULL DEFAULT 'mail',
  name_attr TEXT NOT NULL DEFAULT 'cn',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);


