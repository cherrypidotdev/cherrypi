-- +goose StatementBegin
CREATE FUNCTION tasks_state_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.state_updated_at := NEW.created_at;
  ELSIF NEW.state IS DISTINCT FROM OLD.state THEN
    NEW.state_updated_at := NEW.updated_at;
  END IF;
  RETURN NEW;
END;
$$;
-- +goose StatementEnd

CREATE TRIGGER tasks_state_updated_at_on_insert
BEFORE INSERT ON tasks
FOR EACH ROW EXECUTE FUNCTION tasks_state_updated_at();

CREATE TRIGGER tasks_state_updated_at_on_update
BEFORE UPDATE OF state ON tasks
FOR EACH ROW
WHEN (OLD.state IS DISTINCT FROM NEW.state)
EXECUTE FUNCTION tasks_state_updated_at();
