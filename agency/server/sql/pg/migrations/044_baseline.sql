  updated_at BIGINT NOT NULL,
  model_provider TEXT NOT NULL DEFAULT '',
  model_id TEXT NOT NULL DEFAULT '',
  thinking_level TEXT NOT NULL DEFAULT '',
  interactive BIGINT NOT NULL DEFAULT 0,
  workspace TEXT NOT NULL DEFAULT '',
  auto_title BIGINT NOT NULL DEFAULT 0,
  pending_prompt TEXT NOT NULL DEFAULT '',
  state_updated_at BIGINT NOT NULL DEFAULT 0,
  session_deleted_at BIGINT,
  size TEXT NOT NULL DEFAULT 'medium'
    CHECK (size IN ('small', 'medium', 'big', 'epic')),
  archived_at BIGINT
, creator_actor_id BIGINT, participation TEXT NOT NULL DEFAULT 'project'
  CHECK (participation IN ('project', 'teams', 'assignee')), pending_prompt_actor_id BIGINT);


