CREATE TABLE task_comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_rowid BIGINT NOT NULL REFERENCES tasks (rowid) ON DELETE CASCADE,
  author_actor_id BIGINT REFERENCES actors (id) ON DELETE SET NULL,
  body TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  edited_at BIGINT,
  deleted_at BIGINT,
  deleted_by_actor_id BIGINT REFERENCES actors (id) ON DELETE SET NULL
);
CREATE INDEX idx_task_comments_task ON task_comments (task_rowid, created_at, id);
CREATE INDEX idx_task_comments_author ON task_comments (author_actor_id);

CREATE TABLE task_comment_attachments (
  comment_id BIGINT NOT NULL REFERENCES task_comments (id) ON DELETE CASCADE,
  attachment_id BIGINT NOT NULL REFERENCES attachments (id) ON DELETE CASCADE,
  position BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (comment_id, attachment_id)
);
CREATE INDEX idx_task_comment_attachments_attachment
  ON task_comment_attachments (attachment_id);

CREATE TABLE task_comment_reads (
  task_rowid BIGINT NOT NULL REFERENCES tasks (rowid) ON DELETE CASCADE,
  actor_id BIGINT NOT NULL REFERENCES actors (id) ON DELETE CASCADE,
  last_read_comment_id BIGINT NOT NULL,
  read_at BIGINT NOT NULL,
  PRIMARY KEY (task_rowid, actor_id)
);
CREATE INDEX idx_task_comment_reads_actor ON task_comment_reads (actor_id);

