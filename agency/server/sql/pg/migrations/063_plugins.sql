ALTER TABLE actors DROP CONSTRAINT IF EXISTS actors_kind_check;
ALTER TABLE actors ADD CONSTRAINT actors_kind_check
  CHECK (kind IN ('user', 'agent', 'plugin'));

CREATE TABLE plugins (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  version TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  manifest_json TEXT NOT NULL,
  runtime TEXT NOT NULL DEFAULT 'lua',
  entry TEXT NOT NULL DEFAULT '',
  checksum TEXT NOT NULL DEFAULT '',
  enabled BIGINT NOT NULL DEFAULT 0,
  installed_by_actor_id BIGINT REFERENCES actors (id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);

CREATE TABLE plugin_actors (
  plugin_id TEXT PRIMARY KEY REFERENCES plugins (id) ON DELETE CASCADE,
  actor_id BIGINT NOT NULL UNIQUE REFERENCES actors (id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL
);

CREATE TABLE plugin_settings (
  plugin_id TEXT NOT NULL REFERENCES plugins (id) ON DELETE CASCADE,
  scope TEXT NOT NULL CHECK (scope IN ('org', 'agent', 'user')),
  target_id TEXT NOT NULL DEFAULT '',
  values_json TEXT NOT NULL DEFAULT '{}',
  enabled BIGINT NOT NULL DEFAULT 0,
  updated_by_actor_id BIGINT REFERENCES actors (id) ON DELETE SET NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (plugin_id, scope, target_id)
);

CREATE TABLE plugin_project_settings (
  plugin_id TEXT NOT NULL REFERENCES plugins (id) ON DELETE CASCADE,
  project_id TEXT NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
  enabled BIGINT NOT NULL DEFAULT 0,
  allow_task_creation BIGINT NOT NULL DEFAULT 1,
  max_priority BIGINT NOT NULL DEFAULT 0,
  values_json TEXT NOT NULL DEFAULT '{}',
  updated_by_actor_id BIGINT REFERENCES actors (id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (plugin_id, project_id)
);
CREATE INDEX idx_plugin_project_settings_project ON plugin_project_settings (project_id);

CREATE TABLE task_plugins (
  task_id TEXT PRIMARY KEY REFERENCES tasks (id) ON DELETE CASCADE,
  plugin_id TEXT NOT NULL REFERENCES plugins (id) ON DELETE CASCADE,
  tools_json TEXT NOT NULL DEFAULT '[]',
  created_at BIGINT NOT NULL
);
CREATE INDEX idx_task_plugins_plugin ON task_plugins (plugin_id);

CREATE TABLE plugin_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plugin_id TEXT NOT NULL REFERENCES plugins (id) ON DELETE CASCADE,
  at BIGINT NOT NULL,
  level TEXT NOT NULL,
  kind TEXT NOT NULL,
  invocation_id TEXT NOT NULL DEFAULT '',
  message TEXT NOT NULL,
  data_json TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX idx_plugin_logs_plugin ON plugin_logs (plugin_id, at DESC, id DESC);

